//
// WHY ÊTRE, ELLE OR ELLES, AND JE OR J' ARE ON EXACT CARDS. Word and phrase
// cards are marked with typo tolerance, so when the French is typed a slip of
// a letter or two passes as Close enough: "Elle sont française", "Elle être
// française" and "Elles est française" on "Elle est française"; "Tu êtes
// d'où ?" and "Tu est d'où ?"; "Je es de New York"; "Le nom de ma femme sont
// Linda"; "Pourquoi vous est à Los Angeles ?". On the pronoun cards "elle"
// passes for "they (women only)" and "elles" for "she". "je habite à" and
// "Je habite avec mon mari" pass on their cards, and "Tu es où ?" ("where
// are you?") on "Tu es d'où ?". So each form of être is also asked exactly
// (the six drills, her ex. 1 gaps and her ex. 2 answers), elle and elles by
// the answer-yes cards (Élise → elle, Marie et Hélène → elles), and je or j'
// by two gap cards; the phrase cards are there for meaning. Closing the gap
// on the phrase cards, and between d'où and où, needs a change to the app's
// fuzzy marking, not to this file.
//
// DEPARTURES FROM HER SHEETS
//   - Her ex. 2 key has "Oui, elle est au États-Unis"; the card has aux.
//   - Her ex. 3 nouns stay bare, as in her key (professeur, cours de
//     français, mari, nom, mois, an): un is her Leçon 2's and une her
//     Leçon 3's, so no card here shows or asks for either. Her ex. 3 has
//     "teacher – professeur", and her dialogue has Élise as "ta professeure":
//     the card takes both.
//   - Her ex. 3 "I am – je suis" is the être drill, so it is not a word card.
//     Her "woman/wife – femme" is already Leçon 2's live card "la femme": the
//     skill gives a word in two of her lists to the earlier lesson, but
//     moving a live card would cost students its history, so it stays there.
//   - Her ex. 2 "Vous êtes en France ? Oui, je suis en France" also takes
//     "nous sommes": vous can be one person or several. "Vous êtes ensemble
//     en France ?" takes only nous, as in her key: ensemble means more than
//     one. Every ex. 2 card also takes its answer without the Oui the prompt
//     already shows, as in Leçons 2 to 5, and "depuis 2 mois" also takes
//     deux.
//   - Her ex. 2 "Vous êtes mariés ? Oui, nous…" is not a card: her prompt
//     gives the nous, and without it only the silent -s of mariés says that
//     vous is several people, which a Leçon 1 student can't know.
//   - The two "je ou j'" cards are not an exercise of hers. They are built
//     from her sentences (ex. 4 no. 9 "j'habite à Paris", ex. 1 no. 1 "Je
//     suis américain"), so that the j' rule is marked exactly.
//   - Hints that pin down the French: "Le nom de ma femme est Linda" asks
//     for her structure, "(with le nom de)", as "Ma femme s'appelle Linda" is
//     just as right; "je m'appelle" asks "(with je)", as "mon nom est" is
//     right too. Three hints name a right word only to rule it out, and none
//     of the three is asked for: bien "(not bon)", an "(not année)" and cours
//     de français "(not leçon)".
//   - English answers beside hers, so a right one isn't marked wrong: "I'm
//     living" for j'habite (her ATTENTION box); "I have lived" beside her "I
//     have been living"; "Why are you in Los Angeles? (vous)" beside her "you
//     guys"; "French lesson" and "French course" beside her "French class";
//     "The name of my wife is Linda" and "My wife is called Linda"; "Where do
//     you come from?"; "What are you called?"; "What about you?". The depuis
//     card lists only the "I have" forms: an "I've lived" answer would let
//     "I live…" and "I lived…" through as Close enough, and "I've been
//     living…" and "I've lived…" still pass as Close enough.
//   - Slips no card or note uses, for Laura: "J'abite" (for j'habite) among
